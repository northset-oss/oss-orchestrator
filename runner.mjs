#!/usr/bin/env node
// OSS mission runner — LEAN, practical. Two passes, split at your review gate, so scanning hundreds
// of candidates is fast and the heavyweight Docker receipt is paid ONLY on the fixes you ship.
//
//   PASS 1  SCAN  (default) — recheck (timeline) -> clone at base -> Codex codes in an isolated
//                  clone (filtered env, no host secrets) -> capture diff + PR body. THEN STOP.
//                  No Docker. This is the throughput engine: run it across every candidate.
//   PASS 2  RECEIPT (--receipt) — for each mission you APPROVE after reading its diff: assert the
//                  tree still equals the reviewed commit (head==tested), build the attested receipt
//                  locally (northset-oss run-mission.mjs, Docker), print the exact manual ship.
//
// It never pushes, forks, attests, or opens a PR — that stays the proven manual M-008/M-009 flow,
// printed at the end of the receipt pass.
//
// Usage:
//   node runner.mjs [--only M-010] [--concurrency 4] [--specs <dir>] [--out <dir>] [--replace]  # scan
//   node runner.mjs --receipt [--only M-010] [--specs <dir>] [--out <dir>]                      # ship
//   node runner.mjs --recheck-only [--only M-010]                                               # recheck
// Specs: one JSON per mission in the specs dir (see specs/M-010.example.json). Fields:
//   mission_id, candidate, target_repo, issue_url, base_commit, code_prompt, executor{}, receipt{}
//
// Nothing here is a fortress. It preserves what matters for a solo trusted operator: you review
// every diff and authorize every PR by hand; a timeline recheck guards duplicates. That's it.

